# 测试结果记录工作表（模板）
RESULT_HEADERS = ["用例编号", "所属模块", "执行人", "执行日期", "执行结果", "实际结果/缺陷描述", "关联缺陷编号"]
RESULT_ROWS = [[c[0], c[1], "", "", "", "", ""] for c in CASES]


def build():
    wb = Workbook()

    # ---- 工作表1：禅道导入格式 ----
    ws = wb.active
    ws.title = "测试用例（禅道格式）"
    header_fill = PatternFill("solid", fgColor="0D9488")
    header_font = Font(bold=True, color="FFFFFF", size=11)
    thin = Side(style="thin", color="CCCCCC")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    wrap = Alignment(wrap_text=True, vertical="top")

    for col, title in enumerate(ZEN_HEADERS, 1):
        cell = ws.cell(row=1, column=col, value=title)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = border

    for r, row in enumerate(ZEN_ROWS, 2):
        for c, val in enumerate(row, 1):
            cell = ws.cell(row=r, column=c, value=val)
            cell.alignment = wrap
            cell.border = border
            if r % 2 == 0:
                cell.fill = PatternFill("solid", fgColor="F0FDFA")

    widths = [12, 26, 30, 40, 40, 8, 10, 10, 12, 8, 14]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"

    # ---- 工作表2：测试说明 ----
    ws2 = wb.create_sheet("测试说明")
    ws2.column_dimensions["A"].width = 16
    ws2.column_dimensions["B"].width = 90
    for r, (k, v) in enumerate(NOTE_ROWS, 1):
        a = ws2.cell(row=r, column=1, value=k)
        a.font = Font(bold=True)
        b = ws2.cell(row=r, column=2, value=v)
        b.alignment = wrap
        a.border = border
        b.border = border

    # ---- 工作表3：执行结果记录 ----
    ws3 = wb.create_sheet("执行结果记录")
    for col, title in enumerate(RESULT_HEADERS, 1):
        cell = ws3.cell(row=1, column=col, value=title)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = border
    for r, row in enumerate(RESULT_ROWS, 2):
        for c, val in enumerate(row, 1):
            cell = ws3.cell(row=r, column=c, value=val)
            cell.alignment = wrap
            cell.border = border
    for i, w in enumerate([16, 12, 8, 12, 10, 40, 14], 1):
        ws3.column_dimensions[get_column_letter(i)].width = w
    ws3.freeze_panes = "A2"

    OUT.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUT)
    print(f"已生成：{OUT}")
    print(f"用例总数：{len(CASES)} 条")


if __name__ == "__main__":
    build()
